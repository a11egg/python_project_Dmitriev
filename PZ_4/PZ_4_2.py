#Дано целое число N (> 1). Вывести наибольшее из целых чисел K, для которых сумма
#1 + 2 + ... + K будет меньше или равна N, и саму эту сумму.

n = input("Введите число N (n>1): ")
while True:
    try:
        n = int(n)
        break
    except ValueError:
        print("Введите число!")
        n = input("Введите число N (n>1): ")

if n <= 1:
    print("Число должно быть больше 1!")
    n = input("Введите число N (n>1): ")
else:

    k = 0
    s = 0
while s + k + 1 <= n:
    s += k + 1
    k += 1
print(f"K = {k}")
print(f"Сумма = {s}")



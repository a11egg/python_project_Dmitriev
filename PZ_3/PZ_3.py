#Дано три целых числа. Проверить истинность высказывания "КАЖДОЕ ИЗ ЧИСЕЛ ПОЛОЖИТЕЛЬНО"

a = input("Введите число A: ")
b = input("Введите число B: ")
c = input("Введите число C: ")
while True:
    try:
        a = int(a)
        b = int(b)
        c = int(c)
        break
    except ValueError:
        print("Введите число!")
        a = input("Введите число A: ")
        b = input("Введите число B: ")
        c = input("Введите число C: ")

if a > 0 and b > 0 and c > 0:
    print("Каждое из чисел положительно.")
else:
    print("Не все числа положительны.")
